def _build_408_path_map() -> Dict[str, str]:
    """把 _408_OUTLINE 展开成 {节名或别名: 相对目录}。

    同一个键（节名/别名）只允许出现一次；重复说明大纲配置有误，直接抛错
    而不是让 dict 字面量静默覆盖。
    """
    mapping: Dict[str, str] = {}
    seen: Dict[str, str] = {}

    def _put(key: str, relative_dir: str) -> None:
        normalized = _normalize_alias(key)
        if not normalized:
            raise ValueError(f"408 大纲里出现空的节名/别名（目录 {relative_dir}）")
        existing_dir = seen.get(normalized)
        if existing_dir is not None and existing_dir != relative_dir:
            raise ValueError(
                f"408 大纲节名/别名重复：'{key}' 同时指向 '{existing_dir}' 与 '{relative_dir}'"
            )
        seen[normalized] = relative_dir
        mapping.setdefault(key, relative_dir)

    for module, _slug, chapters in _408_OUTLINE:
        for chapter_dir, sections in chapters:
            for section_dir, aliases in sections:
                for segment in (module, chapter_dir, section_dir):
                    if INVALID_PATH_CHARS_RE.search(segment):
                        raise ValueError(
                            f"408 大纲目录段 '{segment}' 含路径非法字符（/ \\ : * ? \" < > |），"
                            "会被拆成多级目录或被 sanitize 改写；请改名，把原写法放进别名"
                        )
                relative_dir = f"{module}/{chapter_dir}/{section_dir}"
                leaf_name = re.sub(r"^\d{1,3}\s*", "", section_dir).strip()
                _put(leaf_name, relative_dir)
                for alias in aliases:
                    _put(alias, relative_dir)
    return mapping


WRONG_CARD_PATH_MAP["408"] = _build_408_path_map()


